const express=require("express");
const c=require("../controllers/completionController");
const auth=require("../middleware/authMiddleware");
const role=require("../middleware/authorizeRole");
const validate=require("../middleware/validate");
const {invoiceSchema,paymentSchema,stockSchema,payrollSchema}=require("../validators/completionValidator");
const router=express.Router();
router.use(auth);
router.get("/dashboard",c.dashboard);
router.get("/reports/projects",role("Admin","Management","Project Manager"),c.projectReport);
router.get("/reports/financial",role("Admin","Management","Accounts"),c.financialReport);
router.get("/reports/materials",role("Admin","Management","Project Manager","Store Manager"),c.materialReport);
router.get("/reports/payroll",role("Admin","Management","Accounts"),c.payrollReport);
router.get("/clients/:id/statement",role("Admin","Management","Accounts"),c.clientStatement);
router.get("/contractors/:id/statement",role("Admin","Management","Accounts","Project Manager"),c.contractorStatement);
router.get("/sites/:id/material-consumption",role("Admin","Management","Project Manager","Store Manager"),c.siteConsumption);
router.get("/inventory/low-stock",role("Admin","Management","Store Manager"),c.lowStock);
router.post("/invoices",role("Admin","Accounts"),validate(invoiceSchema),c.createInvoice);
router.post("/client-payments",role("Admin","Accounts"),validate(paymentSchema),c.recordClientPayment);
router.post("/issuances/:id/approve",role("Admin","Store Manager"),c.approveIssuance);
router.post("/issuances/:id/reject",role("Admin","Store Manager"),c.rejectIssuance);
router.post("/inventory/receive",role("Admin","Store Manager"),validate(stockSchema),c.receiveMaterial);
router.post("/inventory/damage",role("Admin","Store Manager"),validate(stockSchema),c.damageMaterial);
router.post("/inventory/waste",role("Admin","Store Manager"),validate(stockSchema),c.wasteMaterial);
router.post("/payroll/generate",role("Admin","Accounts"),validate(payrollSchema),c.generatePayroll);
router.post("/payroll/:id/approve",role("Admin"),c.approvePayroll);
router.post("/payroll/:id/pay",role("Admin","Accounts"),c.payPayroll);
module.exports=router;
